using System.Globalization;
using System.Text;
using Ekc.Graph;

namespace Ekc.Analysis;

/// <summary>Markdown for humans and LLMs: CLI output, MCP tool results and PR comments.</summary>
public static class MarkdownRenderer
{
    public const string PrCommentMarker = "<!-- ekc-impact -->";

    public static string Flow(FlowResult flow)
    {
        var sb = new StringBuilder();
        sb.AppendLine(CultureInfo.InvariantCulture, $"### Flow: {flow.Title}");
        sb.AppendLine();
        if (flow.Steps.Count == 0)
        {
            sb.AppendLine("No outgoing behaviour found from this starting point.");
            return sb.ToString();
        }

        foreach (var step in flow.Steps)
        {
            var indent = new string(' ', Math.Min(step.Depth, 12) * 2);
            var marker = step.Kind switch
            {
                FlowStepKind.Entry => "▶",
                FlowStepKind.HttpCall => "→ HTTP",
                FlowStepKind.Publish => "⇢ publish",
                FlowStepKind.Consume => "⇠ consume",
                FlowStepKind.DataWrite => "✎ data",
                FlowStepKind.DataRead => "◎ data",
                FlowStepKind.Dispatch => "↳",
                FlowStepKind.Unresolved => "? HTTP",
                _ => "·",
            };
            var confidence = step.Confidence < 0.99 ? $" _(confidence {step.Confidence:0.00})_" : string.Empty;
            var evidence = step.Evidence is null ? string.Empty : $" — `{step.Evidence.Location()}`";
            sb.AppendLine(CultureInfo.InvariantCulture, $"{indent}- {marker} {step.Description}{confidence}{evidence}");
        }

        if (flow.Truncated)
        {
            sb.AppendLine();
            sb.AppendLine("_Flow truncated; narrow the starting point or raise the limits._");
        }

        return sb.ToString();
    }

    public static string Impact(ImpactReport report, string? title = null, bool forPullRequest = false)
    {
        var sb = new StringBuilder();
        if (forPullRequest)
        {
            sb.AppendLine(PrCommentMarker);
        }

        var icon = report.Risk switch { RiskLevel.High => "🔴", RiskLevel.Medium => "🟠", _ => "🟢" };
        sb.AppendLine(CultureInfo.InvariantCulture, $"### {icon} EKC blast radius: {report.Risk} risk{(title is null ? string.Empty : $" — {title}")}");
        sb.AppendLine();

        if (report.Changed.Count == 0)
        {
            sb.AppendLine("No mapped code was changed (configuration, docs or unmapped files only).");
            return sb.ToString();
        }

        sb.AppendLine(CultureInfo.InvariantCulture, $"**Changed:** {string.Join(", ", report.Changed.Take(12).Select(c => $"`{c.Name}`"))}{(report.Changed.Count > 12 ? $" and {report.Changed.Count - 12} more" : string.Empty)}");
        if (report.RiskReasons.Count > 0)
        {
            sb.AppendLine();
            foreach (var reason in report.RiskReasons)
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"- {reason}");
            }
        }

        Section(sb, "Endpoints whose behaviour changes", report.Endpoints);
        Section(sb, "Callers in other services / gateways", report.Callers);
        Section(sb, "Events affected", report.Topics);
        Section(sb, "Event consumers", report.EventConsumers);
        Section(sb, "Tables written", report.Tables);
        Section(sb, "Other code using those tables", report.DataConsumers);
        Section(sb, "Business rules", report.Rules);
        Section(sb, "Business processes", report.Processes);

        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"**Services:** {(report.Services.Count == 0 ? "—" : string.Join(", ", report.Services))}  ");
        sb.AppendLine(CultureInfo.InvariantCulture, $"**Owners to notify:** {(report.Teams.Count == 0 ? "— (no CODEOWNERS match)" : string.Join(", ", report.Teams.Select(t => "@" + t)))}");
        if (forPullRequest)
        {
            sb.AppendLine();
            sb.AppendLine("<sub>Generated by EKC from static analysis of the code. Confidence below 1.00 marks heuristic links; click evidence to verify.</sub>");
        }

        return sb.ToString();
    }

    public static string Service(ServiceDescription d)
    {
        var sb = new StringBuilder();
        var s = d.Service;
        sb.AppendLine(CultureInfo.InvariantCulture, $"### Service `{s.Name}`");
        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"- **Project:** {s.Properties.GetValueOrDefault("project")} (`{s.Properties.GetValueOrDefault("path")}`), discovered via {s.Properties.GetValueOrDefault("discoveredBy")}");
        sb.AppendLine(CultureInfo.InvariantCulture, $"- **Owners:** {(d.Owners.Count == 0 ? "—" : string.Join(", ", d.Owners.Select(o => "@" + o)))}");
        if (d.Domains.Count > 0)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- **Domain:** {string.Join(", ", d.Domains)}");
        }

        List(sb, "Exposes", d.Endpoints.Select(e => $"`{e.Endpoint.Name}`{(e.Handlers.Count > 0 ? $" → {string.Join(", ", e.Handlers)}" : string.Empty)}"));
        List(sb, "Calls", d.Calls.Select(c => $"{c.Target.ServiceOf() ?? c.Target.Name}: `{c.Target.Name}` (from {c.Via})"));
        List(sb, "Called by", d.CalledBy.Select(c => $"{c.Caller.ServiceOf()}: {c.Caller.Name} → `{c.Endpoint.Name}`"));
        List(sb, "Publishes", d.Publishes.Select(p => $"`{p.Name}`"));
        List(sb, "Subscribes to", d.Subscribes.Select(p => $"`{p.Name}`"));
        List(sb, "Data", d.Tables.Select(t => $"{(t.Writes ? "reads/writes" : "reads")} `{t.Table.Name}` ({t.Table.Properties.GetValueOrDefault("context")})"));
        List(sb, "Infrastructure", d.Resources.Select(r => $"{r.Name} ({r.Properties.GetValueOrDefault("type")})"));
        List(sb, "Depends on (orchestration)", d.DependsOn.Select(r => r.Name));
        List(sb, "Business rules implemented", d.Rules.Select(r => r.Name));
        List(sb, "Business processes", d.Processes.Select(p => p.Name));
        return sb.ToString();
    }

    public static string ServiceList(SystemGraph graph)
    {
        var sb = new StringBuilder();
        sb.AppendLine("| Service | Project | Endpoints | Publishes | Subscribes | Owners |");
        sb.AppendLine("|---|---|---:|---:|---:|---|");
        var describer = new ServiceDescriber(graph);
        foreach (var service in describer.Services())
        {
            var d = describer.Describe(service);
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"| {service.Name} | {service.Properties.GetValueOrDefault("project")} | {d.Endpoints.Count} | {d.Publishes.Count} | {d.Subscribes.Count} | {string.Join(", ", d.Owners)} |");
        }

        return sb.ToString();
    }

    public static string Nodes(IReadOnlyList<Node> nodes, string query)
    {
        if (nodes.Count == 0)
        {
            return $"Nothing in the system map matches `{query}`.";
        }

        var sb = new StringBuilder();
        foreach (var node in nodes.Take(30))
        {
            var where = node.Location();
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"- **{node.Kind}** `{node.Name}`{(node.ServiceOf() is { } s && node.Kind != NodeKind.Service ? $" in {s}" : string.Empty)}{(where.Length > 0 ? $" — `{where}`" : string.Empty)} (id `{node.Id}`)");
        }

        return sb.ToString();
    }

    private static void Section(StringBuilder sb, string heading, IReadOnlyList<ImpactItem> items)
    {
        if (items.Count == 0)
        {
            return;
        }

        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"<details{(items.Count <= 8 ? " open" : string.Empty)}><summary><b>{heading}</b> ({items.Count})</summary>");
        sb.AppendLine();
        foreach (var item in items.OrderByDescending(i => i.Confidence).ThenBy(i => i.Service).ThenBy(i => i.Name).Take(40))
        {
            var service = item.Service is null ? string.Empty : $"**{item.Service}** · ";
            var confidence = item.Confidence < 0.99 ? $" _(confidence {item.Confidence:0.00})_" : string.Empty;
            var evidence = item.Evidence is null ? string.Empty : $" — `{item.Evidence.Location()}`";
            var path = item.Path is null ? string.Empty : $"<br/>&nbsp;&nbsp;via {item.Path}";
            sb.AppendLine(CultureInfo.InvariantCulture, $"- {service}`{item.Name}`: {item.Reason}{confidence}{evidence}{path}");
        }

        if (items.Count > 40)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- … {items.Count - 40} more");
        }

        sb.AppendLine();
        sb.AppendLine("</details>");
    }

    private static void List(StringBuilder sb, string heading, IEnumerable<string> lines)
    {
        var items = lines.ToList();
        if (items.Count == 0)
        {
            return;
        }

        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture, $"**{heading}** ({items.Count})");
        foreach (var line in items)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- {line}");
        }
    }
}
